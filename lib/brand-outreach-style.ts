export function buildShushujiaOutreachGuide(productName = "【产品名】"): string {
  return [
    "蜀黍家建联话术基础规则：",
    ...shushujiaOutreachStyleRules.map((rule, index) => `${index + 1}. ${rule}`),
    "",
    `当前产品名：${productName || "【产品名】"}`,
    "",
    "参考话术样本，只学习语气和结构，不要原句照抄：",
    ...shushujiaOutreachExamples.map((example, index) => `${index + 1}. ${example}`)
  ].join("\n");
}
